static void ssd1306_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    i2c_write(SSD1306_ADDR, buf, 2);
}

static void ssd1306_data_byte(uint8_t value)
{
    uint8_t buf[2] = {0x40, value};
    i2c_write(SSD1306_ADDR, buf, 2);
}

