void ssd1306_clear(void)
{
    ssd1306_set_cursor(0, 0);
    for (uint16_t i = 0; i < 128 * 4; i++) {
        ssd1306_data_byte(0x00);
    }
}

void ssd1306_set_cursor(uint8_t x, uint8_t page)
{
    ssd1306_cmd(0xB0 + (page & 0x03));
    ssd1306_cmd(0x00 + (x & 0x0F));
    ssd1306_cmd(0x10 + ((x >> 4) & 0x0F));
}

void ssd1306_write_char(char c)
{
    if (c < 32 || c > 126) {
        c = '?';
    }
    const uint8_t *glyph = &font5x7[(c - 32) * 5];
    for (uint8_t i = 0; i < 5; i++) {
        ssd1306_data_byte(glyph[i]);
    }
    ssd1306_data_byte(0x00);
}

void ssd1306_write_str(const char *s)
{
    while (*s) {
        ssd1306_write_char(*s++);
    }
}

void ssd1306_write_uint(uint16_t value)
{
    char buffer[6];
    uint8_t pos = 0;

    if (value == 0) {
        ssd1306_write_char('0');
        return;
    }

    while (value > 0 && pos < sizeof(buffer) - 1) {
        buffer[pos++] = (char)('0' + (value % 10));
        value /= 10;
    }
    buffer[pos] = '\0';

    for (int i = (int)pos - 1; i >= 0; i--) {
        ssd1306_write_char(buffer[i]);
    }
}